#!/usr/bin/env python3
"""Generate tests/ota_vectors.h from ota/OTA_VECTORS.json.

The generated header is checked in so the host test does not need Python at
build time.  Run this again after changing ota_ref.py / OTA_VECTORS.json:

    python3 ota/gen_vectors_h.py
"""
import json
import pathlib
import struct
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
VECTORS = HERE / "OTA_VECTORS.json"
OUTPUT = ROOT / "tests" / "ota_vectors.h"


def c_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def packet(name, entry):
    return [
        "#define OTA_VEC_{}_RAW {}".format(name, c_string(entry["raw"])),
        "#define OTA_VEC_{}_WIRE {}".format(name, c_string(entry["wire"])),
    ]


def main():
    with VECTORS.open("r", encoding="utf-8") as handle:
        data = json.load(handle)

    hello_raw = bytes.fromhex(data["hello_resp_ok"]["raw"])
    caps = hello_raw[4]
    max_chunk, = struct.unpack_from("<H", hello_raw, 5)
    slot_size, = struct.unpack_from("<I", hello_raw, 7)

    lines = [
        "// Generated by ota/gen_vectors_h.py from ota/OTA_VECTORS.json.",
        "// Do not edit by hand; re-run the generator instead.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "#define OTA_VEC_SECRET_HEX {}".format(c_string(data["secret_hex"])),
        "#define OTA_VEC_NONCE_HEX {}".format(c_string(data["nonce_hex"])),
        "#define OTA_VEC_IMAGE_LEN {}U".format(data["image_len"]),
        "#define OTA_VEC_IMAGE_SHA256_HEX {}".format(
            c_string(data["image_sha256"])
        ),
        "#define OTA_VEC_MAX_CHUNK {}U".format(max_chunk),
        "#define OTA_VEC_CAPS {}U".format(caps),
        "#define OTA_VEC_SLOT_SIZE 0x{:08X}U".format(slot_size),
        "",
    ]

    for name in (
        "hello",
        "hello_resp_ok",
        "begin",
        "begin_resp_ok",
        "chunk_resp_first",
        "chunk_resp_bad_offset",
        "end",
        "end_resp_ok",
        "abort",
        "bootloader",
        "bad_mac_begin",
    ):
        lines.extend(packet(name.upper(), data[name]))
        lines.append("")

    lines.extend(
        [
            "typedef struct {",
            "    uint32_t offset;",
            "    const char *raw_hex;",
            "    const char *wire_hex;",
            "} ota_vec_chunk_t;",
            "",
            "static const ota_vec_chunk_t OTA_VEC_CHUNKS[] = {",
        ]
    )
    for chunk in data["chunks"]:
        lines.append(
            '    {{{}U, {}, {}}},'.format(
                chunk["offset"],
                c_string(chunk["raw"]),
                c_string(chunk["wire"]),
            )
        )
    lines.extend(
        [
            "};",
            "",
            "#define OTA_VEC_CHUNK_COUNT {}U".format(len(data["chunks"])),
            "",
        ]
    )

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print("wrote {} ({} bytes)".format(OUTPUT, OUTPUT.stat().st_size))
    return 0


if __name__ == "__main__":
    sys.exit(main())
